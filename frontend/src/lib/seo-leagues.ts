export function getSeoLeagueBySlug(slug: string): SeoLeaguePageConfig | null {
  return SEO_LEAGUE_PAGES.find((p) => p.slug === slug) ?? null;
}

export function matchesSeoLeague(config: SeoLeaguePageConfig, prediction: { sport: SportType; leagueName: string }): boolean {
  if (prediction.sport !== config.sportFilter) return false;
  if (config.matchAllSport) return true;
  const name = prediction.leagueName.toLowerCase();
  return config.leagueKeywords.some((keyword) => name.includes(keyword));
}
